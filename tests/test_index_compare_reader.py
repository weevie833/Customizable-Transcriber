"""Regression tests for index_compare/reader.py -- the XLSX-reading half of
Index Compare. Covers the round trip through the app's own writer
(xls_conversion/spreadsheet_export.py:rows_to_xlsx), and the manual-mapping
fallback for a ground-truth file that was never generated by this app -- a
real, not hypothetical, case: an indexer's own corrected index, tracked by
name and date, with no page/act-number column filled in at all."""

from __future__ import annotations

from xls_conversion.ai_parser import RECORD_TYPES
from xls_conversion.spreadsheet_export import rows_to_xlsx

from index_compare.reader import (
    NeedsMapping,
    detect_schema,
    list_worksheets,
    read_rows,
    resolve_index_file,
    suggest_mapping,
)

MATRIMONI = RECORD_TYPES["matrimoni"]


def _blank_row(config) -> dict[str, str]:
    return {field: "" for field in config.fields}


def _matrimoni_xlsx(rows: list[dict[str, str]]) -> bytes:
    return rows_to_xlsx(
        MATRIMONI.group_headers,
        MATRIMONI.column_headers,
        MATRIMONI.fields,
        rows,
        MATRIMONI.sheet_name,
        numeric_columns=MATRIMONI.numeric_columns,
        padded_column=MATRIMONI.padded_column,
        column_widths=list(MATRIMONI.column_widths),
    )


def test_round_trip_through_the_apps_own_writer():
    row = _blank_row(MATRIMONI)
    row.update(
        {
            "page_number": "34",
            "image_number": "005",  # zero-padded column -- see reader._cell_text
            "marriage_year": "1752",
            "marriage_month": "September",
            "marriage_day": "23",
            "groom_given_name": "Giuseppe",
            "groom_last_name": "Rossi",
            "bride_given_name": "Anna",
            "bride_last_name": "Bianchi",
        }
    )
    xlsx_bytes = _matrimoni_xlsx([row])

    infos = list_worksheets(xlsx_bytes)
    assert len(infos) == 1
    assert infos[0].name == MATRIMONI.sheet_name
    assert infos[0].row_count == 1

    detected = detect_schema(infos[0].header_row1, infos[0].header_row2)
    assert detected is not None
    record_type, mapping = detected
    assert record_type == "matrimoni"

    rows = read_rows(xlsx_bytes, infos[0].name, MATRIMONI, mapping)
    assert rows == [row]
    # The zero-padded Image # column must round-trip as "005", not the
    # underlying int 5 openpyxl's own .value would return.
    assert rows[0]["image_number"] == "005"


def test_detect_schema_returns_none_for_an_unrelated_shape():
    # A sheet that matches none of the 6 known schemas at all.
    result = detect_schema(["Notes"], ["Free text"])
    assert result is None


def test_detect_schema_tolerates_whitespace_and_case_but_not_reordering():
    header1 = [h.upper() + "  " for h in MATRIMONI.group_headers]
    header2 = ["  " + h.lower() for h in MATRIMONI.column_headers]
    result = detect_schema(header1, header2)
    assert result is not None
    assert result[0] == "matrimoni"


def test_suggest_mapping_disambiguates_repeated_column_headers():
    """A hand-built ground-truth template, never generated by this app:
    different column names/order than any of the 6 known schemas. Given
    "Given Name" appears once under Groom and once under Bride, a
    field-by-field-in-order assignment can let an earlier, weakly-matching
    field steal the column a later field should have claimed -- this is
    the bug the global-best-first assignment in suggest_mapping() fixes."""
    custom_row1 = ["", "Marriage", "", "Groom", "", "Bride", ""]
    custom_row2 = ["Img#", "Date", "Yr", "Given Name", "Surname", "Given Name", "Surname"]

    assert detect_schema(custom_row1, custom_row2) is None

    mapping = suggest_mapping("matrimoni", custom_row1, custom_row2)
    assert mapping["groom_given_name"] == 3
    assert mapping["groom_last_name"] == 4
    assert mapping["bride_given_name"] == 5
    assert mapping["bride_last_name"] == 6
    # No good match exists for these -- must be left unmapped, not guessed.
    assert mapping["groom_father_given_name"] is None
    assert mapping["bride_father_given_name"] is None


def test_read_rows_with_a_partial_manual_mapping_leaves_unmapped_fields_blank():
    custom_row1 = ["", "Marriage", "", "Groom", "", "Bride", ""]
    custom_row2 = ["Img#", "Date", "Yr", "Given Name", "Surname", "Given Name", "Surname"]
    xlsx_bytes = rows_to_xlsx(
        custom_row1,
        custom_row2,
        ["locator", "date", "year", "g_given", "g_last", "b_given", "b_last"],
        [
            {
                "locator": "5",
                "date": "September",
                "year": "1752",
                "g_given": "Giuseppe",
                "g_last": "Rossi",
                "b_given": "Anna",
                "b_last": "Bianchi",
            }
        ],
        "Custom",
    )
    mapping = suggest_mapping("matrimoni", custom_row1, custom_row2)
    rows = read_rows(xlsx_bytes, "Custom", MATRIMONI, mapping)
    assert len(rows) == 1
    assert rows[0]["groom_given_name"] == "Giuseppe"
    assert rows[0]["bride_last_name"] == "Bianchi"
    # groom_father_given_name had no mapped column -- reads as blank, not
    # an error, so the rest of the row is still usable.
    assert rows[0]["groom_father_given_name"] == ""


def test_read_rows_skips_a_fully_blank_trailing_row():
    row = _blank_row(MATRIMONI)
    row["groom_given_name"] = "Giuseppe"
    blank = _blank_row(MATRIMONI)
    xlsx_bytes = _matrimoni_xlsx([row, blank])
    infos = list_worksheets(xlsx_bytes)
    record_type, mapping = detect_schema(infos[0].header_row1, infos[0].header_row2)
    rows = read_rows(xlsx_bytes, infos[0].name, MATRIMONI, mapping)
    assert len(rows) == 1


def test_resolve_index_file_auto_detects_an_app_shaped_file():
    row = _blank_row(MATRIMONI)
    row["groom_given_name"] = "Giuseppe"
    xlsx_bytes = _matrimoni_xlsx([row])
    config, rows, sheet_name = resolve_index_file(xlsx_bytes)
    assert config.key == "matrimoni"
    assert sheet_name == MATRIMONI.sheet_name
    assert rows == [row]


def test_resolve_index_file_raises_needs_mapping_for_a_custom_template():
    xlsx_bytes = rows_to_xlsx(
        ["", "Groom"],
        ["Loc", "Name"],
        ["locator", "name"],
        [{"locator": "34", "name": "Giuseppe"}],
        "Custom",
    )
    try:
        resolve_index_file(xlsx_bytes)
    except NeedsMapping as exc:
        assert len(exc.worksheets) == 1
        assert exc.worksheets[0].name == "Custom"
    else:
        raise AssertionError("expected NeedsMapping")


def test_resolve_index_file_uses_an_explicit_mapping_when_supplied():
    xlsx_bytes = rows_to_xlsx(
        ["", "Groom"],
        ["Loc", "Name"],
        ["locator", "name"],
        [{"locator": "34", "name": "Giuseppe"}],
        "Custom",
    )
    mapping = suggest_mapping("matrimoni", ["", "Groom"], ["Loc", "Name"])
    config, rows, sheet_name = resolve_index_file(
        xlsx_bytes, {"record_type": "matrimoni", "sheet_name": "Custom", "mapping": mapping}
    )
    assert config.key == "matrimoni"
    assert sheet_name == "Custom"
    assert rows[0]["groom_given_name"] == "Giuseppe"


def test_read_rows_raises_a_clear_error_for_an_unknown_sheet_name():
    xlsx_bytes = _matrimoni_xlsx([_blank_row(MATRIMONI)])
    try:
        read_rows(xlsx_bytes, "Does Not Exist", MATRIMONI, {})
    except RuntimeError as exc:
        assert "Does Not Exist" in str(exc)
    else:
        raise AssertionError("expected a RuntimeError")
